// Writes the Industry Updates artwork's table, app/src/News/art-data.php (docs/DESIGN.md 8.36), which Psc\News\Art
// prints from. It draws every category's four compositions in their three takes, on the card (320 x 180) and on the
// article band (576 x 180), as literal markup, and gives each take its edge map from edges.json. Nothing here runs
// at request time, so the page, the share card and the tests all read the same strings.
//
//   node tools/news-art/build.mjs             the table, from the motifs and edges.json
//   node tools/news-art/edges.mjs             measures each take's edges in a browser and writes edges.json
//
// After a motif changes: build, measure, build again (a take the measure has not seen keeps every edge, and
// NewsAssetsTest refuses the table until it has).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Art, sig } from './lib.mjs';
import { M as MA } from './motifs-a.mjs';
import { M as MB } from './motifs-b.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const M = { ...MA, ...MB };
// Categories::KEYS, in its order.
const KEYS = ['video', 'audio', 'lighting', 'staging', 'production', 'showcalling', 'streaming', 'automation', 'interactive', 'ai', 'technology', 'freelance', 'legal', 'tips'];

const draw = (fn, o) => { const a = new Art(); fn(a, o); return a.out(); };
const table = { card: {}, band: {} };
for (const key of KEYS) {
  if (!M[key] || M[key].length !== 4) throw new Error(`${key}: four compositions`);
  table.card[key] = M[key].map((fn) => [0, 1, 2].map((k) => draw(fn, { W: 320, k })));
  table.band[key] = M[key].map((fn) => [0, 1, 2].map((k) => draw(fn, { W: 576, k })));
}
if (/NaN|undefined|Infinity/.test(JSON.stringify(table))) throw new Error('a number went wrong in a motif');

// Each take's edge map (four digits, one per edge the id asks for): the edge printed instead, the first in that edge's
// order that the take leaves clear, as edges.mjs measured it. A band's edge must suit both its pictures (the band's own
// from 40rem, the card's below). A take edges.json has not measured as drawn keeps every edge until it is measured.
const ORDER = [[0, 2, 1, 3], [1, 3, 2, 0], [2, 0, 3, 1], [3, 1, 0, 2]];
const edgesFile = path.join(here, 'edges.json');
const measured = fs.existsSync(edgesFile) ? JSON.parse(fs.readFileSync(edgesFile, 'utf8')) : { card: {}, band: {} };
const clear = (frame, key, v, k) => { const m = measured[frame]?.[key]?.[v]?.[k]; return m && m.sig === sig(table[frame][key][v][k]) ? m.ok : null; };
let stale = 0;
table.edge = { card: {}, band: {} };
for (const key of KEYS) for (const frame of ['card', 'band']) {
  table.edge[frame][key] = [0, 1, 2, 3].map((v) => [0, 1, 2].map((k) => {
    const c = clear('card', key, v, k), b = frame === 'band' ? clear('band', key, v, k) : c;
    if (!c || !b) { stale++; return '0123'; }
    const ok = c.filter((f) => b.includes(f));
    if (!ok.length) throw new Error(`${key} ${frame} v${v} k${k}: no edge leaves both its pictures clear`);
    return ORDER.map((o) => o.find((f) => ok.includes(f))).join('');
  }));
}

// Single-quoted literals, so nothing in the markup is interpolated; the markup holds no backslash or single quote,
// and the build refuses one if it ever does.
const lit = (s) => { if (/['\\]/.test(s)) throw new Error('a quote or backslash in the markup'); return `'${s}'`; };
const arr = (o) => (Array.isArray(o) ? `[${o.map(arr).join(',')}]` : typeof o === 'string' ? lit(o) : `[${Object.entries(o).map(([k, v]) => `'${k}'=>${arr(v)}`).join(',')}]`);
const out = path.join(root, 'app/src/News/art-data.php');
fs.writeFileSync(out, `<?php\n// Generated by tools/news-art/build.mjs: the artwork's table (docs/DESIGN.md 8.36). Never edit by hand.\nreturn ${arr(table)};\n`);
console.log(`${path.relative(root, out)}: ${KEYS.length} categories, ${fs.statSync(out).size} bytes`);
if (stale) console.warn(`${stale} takes not measured as drawn: run node tools/news-art/edges.mjs, then this again.`);
